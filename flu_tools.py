def cmd_extract_ha(a):
    seg_of_id = {r.id: segment_of(r.description, len(r.seq)) for r in SeqIO.parse(a.ref, "fasta")}
    for rec in SeqIO.parse(a.consensus, "fasta"):
        if (seg_of_id.get(rec.id) or segment_of(rec.description, len(rec.seq))) == "HA":
            SeqIO.write(rec, a.out, "fasta")
            print(f"✅ คัดลอกเซกเมนต์ HA สำเร็จ: {rec.id} ({len(rec.seq)} bp) -> {a.out}")
            return
    die("ไม่พบเซกเมนต์ HA ใน consensus")


