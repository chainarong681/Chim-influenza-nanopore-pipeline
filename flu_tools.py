# -------------------------------------------------------------------- virulence
def longest_orf(seq):
    best = ""
    for s in (seq, seq.reverse_complement()):
        for f in range(3):
            sub = s[f:]
            sub = sub[: len(sub) // 3 * 3]
            for chunk in str(sub.translate()).split("*"):
                i = chunk.find("M")
                if i >= 0 and len(chunk) - i > len(best):
                    best = chunk[i:]
    return best


def assess_ha(seq):
    prot = longest_orf(seq)
    if len(prot) < 450:
        return [("HA", "Cleavage site", "Cannot assess", "badge-secondary",
                 f"ORF ของ HA สั้นผิดปกติ ({len(prot)} aa) อาจมี frameshift/ลำดับไม่ครบ ตรวจด้วยมือ")]
    idx = prot.find("GLF", 300)
    if idx < 0:
        return [("HA", "Cleavage site", "Cannot assess", "badge-secondary", "ไม่พบ motif GLF หลังตำแหน่ง cleavage")]
    basic = sum(c in "RK" for c in prot[max(0, idx - 8):idx])
    motif = f"{prot[max(0, idx - 12):idx]}/{prot[idx:idx + 3]}"
    if basic >= 4:
        st, cls = "HPAI-like multibasic site", "badge-danger"
    elif basic == 3:
        st, cls = "Possible multibasic (ตรวจด้วยมือ)", "badge-warning"
    else:
        st, cls = "Monobasic (LPAI-like)", "badge-success"
    return [("HA", "Cleavage site", st, cls, f"motif: <code>{esc(motif)}</code> (basic R/K ใน 8 aa ก่อน GLF = {basic})")]


def assess_pb2(seq):
    prot = longest_orf(seq)
    if len(prot) < 680:
        return [("PB2", "E627K / D701N", "Cannot assess", "badge-secondary",
                 f"ORF ของ PB2 สั้นผิดปกติ ({len(prot)} aa) ตรวจด้วยมือ")]
    out = []
    for pos, wt, mut in ((627, "E", "K"), (701, "D", "N")):
        aa, ctx = prot[pos - 1], prot[pos - 6:pos + 5]
        if aa == mut:
            st, cls = f"{wt}{pos}{mut} detected", "badge-danger"
        elif aa == wt:
            st, cls = f"{wt}{pos} (wild-type)", "badge-success"
        else:
            st, cls = f"{aa}{pos} (ไม่ใช่ {wt}/{mut})", "badge-warning"
        out.append(("PB2", f"{wt}{pos}{mut}", st, cls, f"residue {pos} = {aa}, context: <code>{esc(ctx)}</code>"))
    return out


def assess_na(seq):
    prot = longest_orf(seq)
    if len(prot) < 350:
        return [("NA", "H275Y (N1)", "Cannot assess", "badge-secondary", f"ORF ของ NA สั้นผิดปกติ ({len(prot)} aa)")]
    m = re.search(r"RSP([HY])RTL", prot)  # motif-based: robust to NA stalk deletions
    if not m:
        return [("NA", "H275Y (N1)", "Motif not found", "badge-warning",
                 "ไม่พบ motif อ้างอิงรอบตำแหน่ง 275 (อาจไม่ใช่ N1 หรือลำดับเพี้ยน) ตรวจด้วยมือ")]
    aa = m.group(1)
    st, cls = ("H275Y detected (oseltamivir resistance)", "badge-danger") if aa == "Y" else ("H275 (wild-type)", "badge-success")
    return [("NA", "H275Y (N1) = H274Y (N2 numbering)", st, cls, f"context: <code>{esc(m.group(0))}</code>")]


def cmd_virulence(a):
    seg_of_id = {r.id: segment_of(r.description, len(r.seq)) for r in SeqIO.parse(a.ref, "fasta")}
    by_seg = {}
    for rec in SeqIO.parse(a.consensus, "fasta"):
        seg = seg_of_id.get(rec.id) or segment_of(rec.description, len(rec.seq))
        if seg:
            by_seg[seg] = rec.seq.upper()
    findings = []
    for seg, fn in (("HA", assess_ha), ("PB2", assess_pb2), ("NA", assess_na)):
        if seg in by_seg:
            findings += fn(by_seg[seg])
        else:
            findings.append((seg, "-", "Segment missing", "badge-secondary", f"ไม่พบเซกเมนต์ {seg} ใน consensus"))
    rows = ""
    print("=== Risk & Virulence Assessment ===")
    for seg, marker, st, cls, detail in findings:
        rows += (f"<tr><td><strong>{esc(seg)}</strong></td><td>{esc(marker)}</td><td>{badge(st, cls)}</td>"
                 f"<td>{detail}</td></tr>")
        print(f"{seg:<4} {marker:<34} {st}")
