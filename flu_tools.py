def fig_b64(fig):
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=130)
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode()


def segment_of(desc, length=0):
    """Guess influenza segment name from a FASTA header (and length as fallback)."""
    m = re.search(r"segment\s*([1-8])\b", desc, re.I)
    if m:
        return SEG_BY_NUMBER[int(m.group(1))]
    d = desc.lower()
    if "pb2" in d:
        return "PB2"
    if "pb1" in d:
        return "PB1"
    if re.search(r"\bpa\b|polymerase acidic", d):
        return "PA"
    if "hemagglutinin" in d or re.search(r"\bha\b", d):
        return "HA"
    if "neuraminidase" in d or re.search(r"\bna\b", d):
        return "NA"
    if "nucleoprotein" in d or re.search(r"\bnp\b", d):
        return "NP"
    if "matrix" in d or re.search(r"\bm1\b|\bm2\b", d):
        return "M"
    if "nonstructural" in d or "nuclear export" in d or re.search(r"\bns[12]?\b", d):
        return "NS"
    for name, lo, hi in LEN_RANGES:
        if lo <= length <= hi:
            return name
    return None


def read_idxstats(path):
    rows = []
    with open(path) as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) == 4 and p[0] != "*":
                rows.append({"ref_id": p[0], "length": int(p[1]), "mapped": int(p[2])})
    return pd.DataFrame(rows, columns=["ref_id", "length", "mapped"])


def read_depth(path):
    return pd.read_csv(path, sep="\t", header=None, names=["ref", "pos", "depth"])


# ---------------------------------------------------------------- fetch-refs
def cmd_fetch_refs(a):
    from Bio import Entrez

    Entrez.email = a.email
    if a.api_key:
        Entrez.api_key = a.api_key
    print("กำลังตรวจสอบจำนวนข้อมูลใน NCBI ...")
    h = Entrez.esearch(db="nucleotide", term=a.query, usehistory="y", retmax=0)
    r = Entrez.read(h)
    h.close()
    total = int(r["Count"])
    print(f"พบข้อมูลทั้งหมด: {total:,} รายการ")
    if total == 0:
        die("ไม่พบข้อมูลที่ตรงกับเงื่อนไข")
    delay = 0.11 if a.api_key else 0.35
    with open(a.out, "w") as out:
        for start in range(0, total, 500):
            for attempt in range(1, 4):
                try:
                    h = Entrez.efetch(db="nucleotide", rettype="fasta", retmode="text",
                                      retstart=start, retmax=500,
                                      webenv=r["WebEnv"], query_key=r["QueryKey"])
                    out.write(h.read())
                    h.close()
                    break
                except Exception as e:  # network hiccups are common with NCBI
                    print(f"  retry {attempt}/3 ที่ index {start}: {e}")
                    time.sleep(2 * attempt)
            else:
                die(f"ดาวน์โหลดล้มเหลวที่ index {start}")
            time.sleep(delay)
            print(f"  ดาวน์โหลดแล้ว {min(start + 500, total):,} / {total:,}")
    print(f">>> บันทึก {a.out} เรียบร้อย")


# ------------------------------------------------------------------- readlen
def cmd_readlen(a):
    lengths = [len(r.seq) for r in SeqIO.parse(a.fastq, "fastq")]
    if not lengths:
        die("filtered.fastq ว่างเปล่า")
    s = pd.Series(lengths)
    fig, ax = plt.subplots(figsize=(10, 5))
    ax.hist(lengths, bins=60, color="#2ca02c", edgecolor="black", alpha=0.7)
    ax.axvline(a.min_len, color="r", linestyle="--", label=f"Minimum length cutoff ({a.min_len} bp)")
    ax.set_title(f"Read length distribution after QC (n={len(s):,}, median={s.median():,.0f} bp)")
    ax.set_xlabel("Read length (bp)")
    ax.set_ylabel("Read count")
    ax.legend()
    fig.tight_layout()
    fig.savefig(a.out, dpi=200)
    print(f"Saved: {a.out}  (reads={len(s):,}, median length={s.median():,.0f} bp)")


# ----------------------------------------------------------------- select-ref
def cmd_select_ref(a):
    desc = {r.id: r.description for r in SeqIO.parse(a.candidates, "fasta")}
    df = read_idxstats(a.idxstats)
    if df.empty or df["mapped"].sum() == 0:
        die("ไม่มี read ใดแมพกับ candidate refs เลย ตรวจสอบ filtered.fastq / candidate_refs.fasta")
    df["description"] = df["ref_id"].map(desc).fillna(df["ref_id"])
    df["segment"] = [segment_of(d, n) or "?" for d, n in zip(df["description"], df["length"])]
    df = df.sort_values("mapped", ascending=False).reset_index(drop=True)
    hit = df[df["mapped"] > 0]

    with open("matched_segment_summary.txt", "w", encoding="utf-8") as out:
        out.write("=== Influenza A Mapped Reads Matched with Candidate FASTA Headers ===\n")
        out.write(f"{'Segment':<8} | {'Reference ID / Full Header':<95} | {'Length':>8} | {'Mapped':>8}\n")
        out.write("-" * 130 + "\n")
        for _, r in hit.iterrows():
            out.write(f"{r['segment']:<8} | {r['description'][:95]:<95} | {r['length']:>8,} | {r['mapped']:>8,}\n")
    print(">>> บันทึก matched_segment_summary.txt")

    top = hit.head(25).iloc[::-1]
    fig, ax = plt.subplots(figsize=(12, max(5, len(top) * 0.35)))
    ax.barh([f"{s} | {d[:55]}" for s, d in zip(top["segment"], top["description"])],
            top["mapped"], color="#2ca02c", edgecolor="black", alpha=0.8)
    ax.set_title("Mapped reads per reference (top 25, primary alignments)")
    ax.set_xlabel("Number of mapped reads")
    fig.tight_layout()
    fig.savefig("matched_segments_plot.png", dpi=150)
    plt.close(fig)

    best = {}
    for _, r in hit[hit["segment"] != "?"].iterrows():
        best.setdefault(r["segment"], r)  # df already sorted by mapped desc
    if not best:
        die("จัดกลุ่มเซกเมนต์จาก header ไม่ได้ กรุณาสร้าง selected_reference.fasta ด้วยมือ (ดู matched_segment_summary.txt)")
    index = SeqIO.index(a.candidates, "fasta")
    SeqIO.write([index[best[s]["ref_id"]] for s in SEG_ORDER if s in best], a.out_ref, "fasta")
    index.close()

    print(f"\n--- Best reference ต่อเซกเมนต์ (เขียนลง {a.out_ref}) ---")
    for s in SEG_ORDER:
        if s in best:
            r = best[s]
            print(f"{s:<4} {r['mapped']:>8,} reads  {r['ref_id']}  {r['description'][:70]}")
        else:
            print(f"{s:<4} [WARNING] ไม่พบ read แมพกับเซกเมนต์นี้เลย")


# ------------------------------------------------------------------- coverage
def cmd_coverage(a):
    names = {r.id: r.description for r in SeqIO.parse(a.ref, "fasta")}
    df = read_depth(a.depth)
    if df.empty:
        die("coverage_depth.txt ว่างเปล่า")
    rows, cards = "", ""
    for ref, g in df.groupby("ref", sort=False):
        mean, mx = g["depth"].mean(), int(g["depth"].max())
        breadth = (g["depth"] >= a.min_depth).mean() * 100
        zero = int((g["depth"] == 0).sum())
        seg = segment_of(names.get(ref, ""), len(g)) or "?"
        cls = "badge-success" if breadth >= 95 else ("badge-warning" if breadth >= 80 else "badge-danger")
        rows += (f"<tr><td><strong>{esc(seg)}</strong></td><td>{esc(ref)}</td><td>{len(g):,}</td>"
                 f"<td>{mean:.1f}x</td><td>{mx:,}x</td><td>{badge(f'{breadth:.1f}%', cls)}</td><td>{zero:,}</td></tr>")
        fig, ax = plt.subplots(figsize=(11, 3.2))
        ax.plot(g["pos"], g["depth"], color="#1f77b4", linewidth=1.2)
        ax.fill_between(g["pos"], g["depth"], color="#1f77b4", alpha=0.25)
        ax.axhline(mean, color="#e74c3c", linestyle="--", linewidth=1.2, label=f"Mean {mean:.1f}x (Max {mx:,}x)")
        ax.axhline(a.min_depth, color="#7f8c8d", linestyle=":", linewidth=1, label=f"Min depth {a.min_depth}x")
        ax.set_title(f"Coverage profile: {seg} - {ref}", fontsize=11, fontweight="bold")
        ax.set_xlabel("Genome position (bp)")
        ax.set_ylabel("Depth")
        ax.legend(loc="upper right", fontsize=9)
        ax.grid(True, linestyle=":", alpha=0.6)
        fig.tight_layout()
        cards += (f'<div class="card"><strong>{esc(names.get(ref, ref))}</strong><br>'
                  f'<img src="data:image/png;base64,{fig_b64(fig)}" alt="{esc(ref)}"></div>')
    table = ("<table><thead><tr><th>Segment</th><th>Ref ID</th><th>Length</th><th>Mean depth</th><th>Max depth</th>"
             f"<th>Breadth &ge;{a.min_depth}x</th><th>Zero-depth positions</th></tr></thead><tbody>{rows}</tbody></table>")
    save_html(a.out, page("Influenza A - Coverage Depth Analysis Report",
                          meta_html(**{"Reference": f"<code>{esc(a.ref)}</code>", "Min depth": f"{a.min_depth}x"}),
                          table + cards))


# --------------------------------------------------------------- consensus-qc
def cmd_consensus_qc(a):
    refs = {r.id: r for r in SeqIO.parse(a.ref, "fasta")}
    cons = {r.id: r for r in SeqIO.parse(a.consensus, "fasta")}
    depth = read_depth(a.depth) if a.depth else pd.DataFrame(columns=["ref", "pos", "depth"])
    breadth = {k: (g["depth"] >= a.min_depth).mean() * 100 for k, g in depth.groupby("ref")}
    print("=== รายงานตรวจสอบคุณภาพลำดับ Consensus (Length / N / Coverage breadth) ===")
    rows = ""
    for rid, ref in refs.items():
        seg = segment_of(ref.description, len(ref.seq)) or "?"
        ref_len = len(ref.seq)
        if rid not in cons:
            rows += (f"<tr><td><strong>{esc(seg)}</strong></td><td>{esc(rid)}</td><td>{ref_len:,}</td>"
                     f"<td colspan='4'>{badge('Missing segment', 'badge-danger')}</td></tr>")
            print(f"{seg:<4} {rid:<14} MISSING")
            continue
        seq = str(cons[rid].seq).upper()
        n = seq.count("N")
        b = breadth.get(rid)
        status, cls = "Normal (สมบูรณ์ดี)", "badge-success"
        if len(seq) < ref_len * 0.85:
            status, cls = "Truncated (สั้นเกินไป)", "badge-warning"
        elif len(seq) > ref_len * 1.15:
            status, cls = "Too long (ยาวผิดปกติ)", "badge-warning"
        elif n > ref_len * 0.05:
            status, cls = "High gaps (N สูง)", "badge-warning"
        elif b is not None and b < 95:
            status, cls = f"Low coverage (<95% ที่ {a.min_depth}x)", "badge-warning"
        b_txt = "-" if b is None else f"{b:.1f}%"
        rows += (f"<tr><td><strong>{esc(seg)}</strong></td><td>{esc(rid)}</td><td>{ref_len:,} bp</td>"
                 f"<td>{len(seq):,} bp</td><td>{n:,} ({n / len(seq) * 100:.2f}%)</td><td>{b_txt}</td>"
                 f"<td>{badge(status, cls)}</td></tr>")
        print(f"{seg:<4} {rid:<14} ref={ref_len:,} cons={len(seq):,} N={n} breadth={b_txt}  -> {status}")
    body = ("<table><thead><tr><th>Segment</th><th>ID</th><th>Ref length</th><th>Consensus length</th>"
            f"<th>N count</th><th>Breadth &ge;{a.min_depth}x</th><th>Status</th></tr></thead><tbody>{rows}</tbody></table>"
            "<p class='note'>หมายเหตุ: Medaka อาจเติมบริเวณที่ไม่มี read ด้วยลำดับจาก reference ทำให้จำนวน N ต่ำกว่าความเป็นจริง "
            "จึงควรดูคอลัมน์ Breadth (สัดส่วนตำแหน่งที่ depth ถึงเกณฑ์) ประกอบเสมอ</p>")
    save_html(a.out, page("Influenza A - Structural & Consensus QC Report",
                          meta_html(**{"Reference": f"<code>{esc(a.ref)}</code>",
                                       "Consensus": f"<code>{esc(a.consensus)}</code>",
                                       "Medaka model": esc(a.model)}), body))


